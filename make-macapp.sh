#!/usr/bin/env bash
# Build dist/Panorama.app: a double-clickable, dockable launcher for Panorama.
#
# It regenerates the web icons from static/icon.svg, builds an .icns for the
# app, and writes a small .app bundle whose launcher makes sure the server is
# running (starting it with `uv` if not) and then opens a chromeless window.
#
# This is a build helper in the spirit of be.kevalo.panorama.plist: the machine
# paths (uv, project dir, port) are baked in here so nothing machine-specific is
# committed. Re-run it after moving the project or changing the port.
#
# Note: with a Chromium-family browser the window rides that browser's Dock
# icon. For a standalone Panorama Dock icon, use Safari's File -> Add to Dock
# (or Chrome's ... -> Cast, save, and share -> Install), which use the manifest.
set -euo pipefail

PROJECT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DIST="$PROJECT/dist"
APP="$DIST/Panorama.app"
SVG="$PROJECT/static/icon.svg"

# --- resolve the machine bits ------------------------------------------------
UV="$(command -v uv || true)"
[ -n "$UV" ] || { echo "error: 'uv' not found on PATH. Install it or edit this script." >&2; exit 1; }
command -v rsvg-convert >/dev/null || { echo "error: 'rsvg-convert' not found (brew install librsvg)." >&2; exit 1; }
[ -f "$SVG" ] || { echo "error: $SVG is missing." >&2; exit 1; }

# Port: prefer PORT from the environment, then panorama.env, else the default.
PORT="${PORT:-}"
if [ -z "$PORT" ] && [ -f "$PROJECT/panorama.env" ]; then
  PORT="$(sed -n 's/^PORT=//p' "$PROJECT/panorama.env" | tail -1)"
fi
PORT="${PORT:-8787}"

echo "project : $PROJECT"
echo "uv      : $UV"
echo "port    : $PORT"

# --- regenerate the web icons from the master SVG ----------------------------
rsvg-convert -w 192 -h 192 "$SVG" -o "$PROJECT/static/icon-192.png"
rsvg-convert -w 512 -h 512 "$SVG" -o "$PROJECT/static/icon-512.png"
rsvg-convert -w 180 -h 180 "$SVG" -o "$PROJECT/static/apple-touch-icon-180.png"
rsvg-convert -w  32 -h  32 "$SVG" -o "$PROJECT/static/favicon-32.png"

# --- build the .icns for the bundle ------------------------------------------
ICONSET="$(mktemp -d)/panorama.iconset"
mkdir -p "$ICONSET"
for size in 16 32 128 256 512; do
  rsvg-convert -w "$size"          -h "$size"          "$SVG" -o "$ICONSET/icon_${size}x${size}.png"
  rsvg-convert -w "$((size * 2))"  -h "$((size * 2))"  "$SVG" -o "$ICONSET/icon_${size}x${size}@2x.png"
done

# --- assemble the bundle -----------------------------------------------------
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/panorama.icns"
rm -rf "$(dirname "$ICONSET")"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>Panorama</string>
    <key>CFBundleDisplayName</key><string>Panorama</string>
    <key>CFBundleIdentifier</key><string>be.kevalo.panorama.app</string>
    <key>CFBundleVersion</key><string>1</string>
    <key>CFBundleShortVersionString</key><string>1.0</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleExecutable</key><string>panorama</string>
    <key>CFBundleIconFile</key><string>panorama</string>
    <key>LSMinimumSystemVersion</key><string>12.0</string>
    <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/panorama" <<LAUNCHER
#!/bin/bash
# Generated by make-macapp.sh. Edit that script and re-run, not this file.
set -u
PORT="$PORT"
UV="$UV"
PROJECT="$PROJECT"
URL="http://127.0.0.1:\${PORT}"
PROFILE="\$HOME/Library/Application Support/Panorama"

up() { /usr/bin/curl -sf -o /dev/null --max-time 1 "\$URL/api/settings"; }

# Start the server if it is not already up (launchd normally keeps it running).
if ! up; then
  ( cd "\$PROJECT" && "\$UV" run app.py >>/tmp/panorama.log 2>&1 & )
  for _ in \$(seq 1 50); do up && break; sleep 0.2; done
fi

# If the app window is already open, just raise it. A second --app launch on the
# same profile is forwarded to the running instance, which opens a plain browser
# window instead of an app window; focusing by unix id sidesteps that entirely.
PID="\$(pgrep -f -- "--app=\$URL --user-data-dir=\$PROFILE" | head -1)"
if [ -n "\$PID" ]; then
  /usr/bin/osascript -e "tell application \"System Events\" to set frontmost of (first process whose unix id is \$PID) to true" >/dev/null 2>&1
  exit 0
fi

# Open a chromeless window in whichever Chromium-family browser is installed.
# A dedicated profile guarantees a fresh app window even when the browser is
# already running (otherwise --app is swallowed by the existing instance). The
# board needs no login, so an isolated profile is fine.
for browser in "Google Chrome" "Brave Browser" "Chromium" "Microsoft Edge"; do
  BIN="/Applications/\$browser.app/Contents/MacOS/\$browser"
  if [ -x "\$BIN" ]; then
    exec "\$BIN" --app="\$URL" --user-data-dir="\$PROFILE" --window-size=1280,860 >/dev/null 2>&1
  fi
done
# No Chromium browser: fall back to the default browser (with normal chrome).
exec /usr/bin/open "\$URL"
LAUNCHER
chmod +x "$APP/Contents/MacOS/panorama"

echo
echo "Built $APP"
echo "Drag it into /Applications and/or keep it in the Dock."
